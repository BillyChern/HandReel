"""Recompute the held-out test's aggregate values from per-unit errors you regenerate, with the released statistic code.

    python reproduce/e1_verdict_from_scores.py [--scores reproduce/heldout/unit_errors_est.json]
        [--thresholds reproduce/heldout/e1-power-size.json] [--json out.json]

This release ships no per-unit error derived from HOI4D or DexYCB ground truth. Regenerate the per-unit file after
acquiring the datasets, with `reproduce/heldout/regenerate_unit_errors.py` (one row per assigned unit: unit, corpus,
cluster, stratum, whether the unit was run (DO AS I DO began an attempt on it; amendment A-V of the protocol: the
35 baseline start refusals count as not run although HandReel processed them), whether the registered analysis removed it, and for each pipeline whether
it delivered and its mean object-centre error in mm). Without that file, and without `--scores`, this script prints
that the check is skipped and exits 0.

It reads the size-calibrated thresholds (`e1-power-size.json`, read by `run/study/e1_stats.load_thresholds`). The
analysis is `run/study/e1_stats.summarise`, unchanged, on the analysed units: the units that ran, without the two
DexYCB units that the protocol's amendment A-T2/A-W removes from both pipelines (INFRA-UNRESOLVED). Completeness (at least
80% of the assigned units run) is taken from all assigned units, as the registered analysis did. B = 10,000
cluster-bootstrap draws, seed 1 (the module defaults). The numbers are formatted by `run/paper/e1_table.py` (`_ratio`,
`_ci`), the code that writes the paper's held-out macros.

It prints, per corpus, six aggregate values (estimated intrinsics): analysed/assigned units; units delivered by
HandReel/DO AS I DO/both; the error ratio with its two-sided 95% bootstrap interval and the verdict (`mitt`: a failure
to deliver counts as an error, a joint failure as a tie); the ratio and interval on the units both delivered
(`complete_case`); the counts of units both delivered with a mean centre error within 50 mm; and the median centre
error in mm, HandReel/DO AS I DO, over the units both delivered (the median over units of each unit's mean error). It
then compares each value with its reference (`PRINTED`, the aggregate values of the authors' registered analysis) and
exits 0 only if every value matches at the printed rounding. The submitted main paper prints `mitt` and `median_mm`
in its Table 1 and the counts of `analysed` and `delivered` in its Secs. 5.1 and 5.2; it does not print
`complete_case` or `within_50mm` (`reproduce/heldout/README.md`). Errors from your own runs match only as far as your
runs reproduce the registered ones.

This recomputes the verdict from per-unit errors. It does not rerun either pipeline, the scorer, the QC decisions or
the unit exclusions, and it does not check that the errors are correct.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "run" / "study"))
sys.path.insert(0, str(ROOT / "run" / "paper"))
import e1_stats as ST
import e1_table as ET

HELDOUT = ROOT / "reproduce" / "heldout"
DEFAULT_SCORES = HELDOUT / "unit_errors_est.json"        # regenerated by the user; never shipped
FORMAT = "handreel.heldout_unit_errors"
VERDICTS = {"NON-INFERIOR": "NI", "INFERIOR": "inferior", "INCONCLUSIVE": "inconclusive", "INCOMPLETE": "incomplete"}
# Reference values: the aggregate values of the authors' registered analysis, with estimated intrinsics. The submitted
# main paper prints `mitt` and `median_mm` in its Table 1 and the `analysed` and `delivered` counts in its text. `mitt`
# carries the verdict (NI); Table 1 marks the DexYCB verdict as not robust, which no statistic here computes.
PRINTED: dict[str, dict[str, str]] = {
    "H": {"analysed": "58/72", "delivered": "58/49/49", "mitt": "0.50 [0.33, 0.63], NI",
          "complete_case": "0.56 [0.45, 0.72]", "within_50mm": "ours 21/49, DO AS I DO 4/49",
          "median_mm": "56.8/101.3"},
    "D": {"analysed": "85/108", "delivered": "58/69/48", "mitt": "0.85 [0.58, 1.00], NI",
          "complete_case": "0.60 [0.51, 0.78]", "within_50mm": "ours 8/48, DO AS I DO 4/48",
          "median_mm": "76.6/112.5"},
}
NAMES = {"H": "HOI4D", "D": "DexYCB"}


def load_rows(path: Path) -> list[dict[str, Any]]:
    doc = json.loads(path.read_text())
    if doc.get("format") != FORMAT or doc.get("version") != 1:
        raise SystemExit(f"{path}: not a {FORMAT} v1 file (write it with reproduce/heldout/regenerate_unit_errors.py)")
    return doc["rows"]


UNAVAILABLE = "unavailable"
NO_PAIR = "unavailable: no unit delivered by both"


def _end(v: Any) -> str:
    """One end of an interval stored on the log-ratio scale. An upper bound that the failure sentinel dominates
    can be past the largest float once exponentiated; it is named, never raised and never printed as a number. A
    very negative bound does not raise: it prints as 0.00, like any ratio below 0.005."""
    try:
        return f"{math.exp(float(v)):.2f}"
    except OverflowError:
        return "above the float range"


def ratio_interval(block: dict[str, Any]) -> str:
    """`ratio [lo, hi]` of one analysis block, formatted as `run/paper/e1_table.py` does for finite values. A block
    without a ratio (no unit in it, or a median past the float range) is `unavailable`; so is a missing interval."""
    if block.get("ratio") is None:
        return UNAVAILABLE
    ci = block.get("ci95")
    interval = UNAVAILABLE if not ci or None in ci else "[" + ", ".join(_end(v) for v in ci) + "]"
    return f"{ET._ratio(block['ratio'])} {interval}"


def cells(rows: list[dict[str, Any]], thresholds: dict[str, dict[str, float]]) -> dict[str, dict[str, str]]:
    """The aggregate values per corpus, from `e1_stats.summarise` on the analysed units."""
    analysed = [r for r in rows if r["run"] and r["removed"] is None]
    out = ST.summarise(analysed, thresholds)
    res: dict[str, dict[str, str]] = {}
    for c in ("H", "D"):
        assigned = [r for r in rows if r["corpus"] == c]
        n_run = sum(1 for r in assigned if r["run"])
        if n_run / len(assigned) < ST.MIN_RUN_FRACTION:
            raise SystemExit(f"{c}: fewer than 80% of the assigned units ran; the corpus would be INCOMPLETE")
        k = out["corpora"][c]
        cc = k["counts_complete_case"]
        both = [r for r in analysed if r["corpus"] == c and r["ours"]["delivered"] and r["theirs"]["delivered"]]
        if len(both) != k["n_both"]:
            raise SystemExit(f"{c}: {len(both)} units both delivered here, {k['n_both']} in the analysis")
        # With no unit delivered by both pipelines the registered failure-rule ratio (`mitt`) still exists, and the
        # complete-case ratio, the within-50 mm counts and the medians do not: they are named as unavailable.
        if both:
            med_o = float(np.median([r["ours"]["e_mm"] for r in both]))
            med_t = float(np.median([r["theirs"]["e_mm"] for r in both]))
            within = (f"ours {cc['good_ours']['count']}/{k['n_both']}, "
                      f"DO AS I DO {cc['good_theirs']['count']}/{k['n_both']}")
            medians = f"{med_o:.1f}/{med_t:.1f}"
        else:
            within = medians = NO_PAIR
        res[c] = {"analysed": f"{k['itt']['n']}/{len(assigned)}",
                  "delivered": f"{k['delivered_ours']}/{k['delivered_theirs']}/{k['n_both']}",
                  "mitt": f"{ratio_interval(k['itt'])}, {VERDICTS[k['verdict']]}",
                  "complete_case": ratio_interval(k["complete_case"]) if both else NO_PAIR,
                  "within_50mm": within, "median_mm": medians}
    return res


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--scores", type=Path, help=f"the per-unit error file (default {DEFAULT_SCORES.name}, if present)")
    ap.add_argument("--thresholds", type=Path, default=HELDOUT / "e1-power-size.json")
    ap.add_argument("--json", type=Path, help="also write the cells and the comparison as JSON")
    a = ap.parse_args(argv)
    if a.scores is None:
        if not DEFAULT_SCORES.is_file():
            print(f"skipped: {DEFAULT_SCORES.relative_to(ROOT)} is not in this release (per-unit errors derived "
                  "from HOI4D and DexYCB ground truth are never shipped). Regenerate it after acquiring the datasets with "
                  "reproduce/heldout/regenerate_unit_errors.py, then rerun this command.")
            return 0
        a.scores = DEFAULT_SCORES
    elif not a.scores.is_file():
        print(f"e1_verdict_from_scores: {a.scores} not found", file=sys.stderr)
        return 2
    got = cells(load_rows(a.scores), ST.load_thresholds(a.thresholds))
    ok = True
    for c, row in got.items():
        print(f"{NAMES[c]}:")
        for key, value in row.items():
            match = value == PRINTED[c][key]
            ok &= match
            print(f"  {key:14s} {value:32s} {'matches the reference' if match else 'DIFFERS from the reference: ' + PRINTED[c][key]}")
    print("ok: every value matches its reference" if ok else "FAIL: a value differs from its reference")
    if a.json:
        a.json.write_text(json.dumps({"cells": got, "printed": PRINTED, "ok": ok}, indent=1) + "\n")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())

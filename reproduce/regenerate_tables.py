"""Print the paper source's generator tables from their records and compare them with the expected hashes.

    python reproduce/regenerate_tables.py --out <new or empty dir>
    python reproduce/regenerate_tables.py --paper-src <paper source dir> --out <new or empty dir>

Without `--paper-src` (the released check) it uses only this folder: every record marked "RELEASED" in
`reproduce/manifest.json` must be in `reproduce/records/` with its pinned sha256 (under its `release_path`, a
descriptive name, when the manifest gives one; `path` is always the paper source's name), `reproduce/make_released_tables.py`
regenerates the five tables those records support into `<out>/tables/`, and each is compared with the paper
generator's output at the pinned paper-source revision without its `%` comment lines (`released.content_sha256` in the
manifest). The paper source writes the tables of the paper's main text by hand, so a match covers the generator's
tables, not a table of the paper's main text. The comment lines are left out
because the paper's generator writes provenance comments that name files which are not released.

With `--paper-src`, the check needs the paper source tree (the directory holding `tools/make_tables.py` and
`records/`). It is never written to: the generator and the records are copied into `<out>/work/paper3/` first, the
generator runs there (`python -I tools/make_tables.py`, as its own docstring says) and writes
`<out>/work/paper3/tables/`. The held-out test macros (`e1_results.tex`) are regenerated by `run/paper/e1_table.py`
from the copied verdict record.

Every input and output is checked against `reproduce/manifest.json`: the generator and each record must have the
pinned sha256 (unless `--allow-unpinned`), and each expected output must match its sha256. For `e1_results.tex` the
first line (a comment naming the verdict path) is excluded from the comparison. The report goes to
`<out>/report.json`. Exit code 0 only when every pinned input matches and every expected output matches.

This is a printing step: it re-reads stored records (aggregates, and the per-unit score records some tables
read). It does not rerun any experiment, scorer, timing or quality check, and a match does not show that the records
themselves are correct.

Re-pinning to another paper revision is one command:

    python reproduce/regenerate_tables.py --paper-src <paper source at REV> --out <new dir> --repin REV

It runs the same steps without the input check, then rewrites `--manifest` (default `reproduce/manifest.json`):
`paper_revision` = REV, the generator's and every record's sha256 and size, and every expected output's sha256 as
regenerated. Each record keeps its release status (a record new to the paper source gets "NOT RELEASED"), each
output keeps its label and the records it reads, and a table the generator writes that the manifest did not list
is added with the label "appendix". Run the command again without `--repin` to confirm the new pins.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
MANIFEST = HERE / "manifest.json"
E1_TABLE = REPO / "run" / "paper" / "e1_table.py"
RELEASED = HERE / "make_released_tables.py"
COMMENT_LINE = re.compile(r"^[ \t]*%.*(?:\n|$)", re.MULTILINE)


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def sha256_body(path: Path) -> str:
    """sha256 of the file without its first line (the generated-from comment)."""
    data = path.read_bytes()
    return hashlib.sha256(data.split(b"\n", 1)[1] if b"\n" in data else b"").hexdigest()


def sha256_content(path: Path) -> str:
    """sha256 of a generated table without its LaTeX comment lines (lines whose first non-blank character is %)."""
    return hashlib.sha256(COMMENT_LINE.sub("", path.read_text()).encode()).hexdigest()


def released_check(out: Path, manifest: dict[str, Any]) -> dict[str, Any]:
    """The released check (module docstring): the shipped records, then the tables they support."""
    shipped = [r for r in manifest["records"] if r["release"].startswith("RELEASED")]
    inputs = []
    for r in shipped:
        f = HERE / r.get("release_path", r["path"])
        got = sha256_file(f) if f.is_file() else None
        inputs.append({"path": f"reproduce/{r.get('release_path', r['path'])}", "expected": r["sha256"], "found": got,
                       "ok": got == r["sha256"]})
    listed = {(HERE / r.get("release_path", r["path"])).resolve() for r in shipped}
    extra = sorted(p.relative_to(HERE).as_posix() for p in (HERE / "records").rglob("*")
                   if p.is_file() and p.resolve() not in listed) if (HERE / "records").is_dir() else []
    report: dict[str, Any] = {"mode": "released", "paper_revision": manifest["paper_revision"], "inputs": inputs,
                              "unlisted_files": extra, "runs": [], "outputs": [], "ok": False}
    if extra or not all(r["ok"] for r in inputs):
        report["error"] = "input sha256 mismatch, missing record or unlisted file in reproduce/records/"
        return report
    report["runs"].append(run([sys.executable, "-I", str(RELEASED), "--out", str(out / "tables")], out))
    for o in manifest["outputs"]:
        if "released" not in o:
            continue
        name = o["released"].get("file", o["file"])          # the released generator's file name for this table
        f = out / name
        got = sha256_content(f) if f.is_file() else None
        want = o["released"]["content_sha256"]
        report["outputs"].append({"file": name, "exhibits": o.get("exhibits", []), "compare": "content",
                                  "expected": want, "found": got, "ok": got == want})
    report["ok"] = bool(report["outputs"]) and report["runs"][0]["rc"] == 0 and all(r["ok"] for r in report["outputs"])
    return report


def check_inputs(src: Path, manifest: dict[str, Any]) -> list[dict[str, Any]]:
    """One row per pinned input (the generator and every record): expected and found sha256."""
    rows = []
    gen = manifest["generator"]
    pinned = [(gen["path"], gen["sha256"])] + [(r["path"], r["sha256"]) for r in manifest["records"]]
    for rel, want in pinned:
        f = src / rel
        got = sha256_file(f) if f.is_file() else None
        rows.append({"path": rel, "expected": want, "found": got, "ok": got == want})
    return rows


def stage(src: Path, work: Path, manifest: dict[str, Any]) -> None:
    """Copy the generator and the records into `work` (a fresh copy of the paper source layout); the source is
    only read."""
    (work / "tools").mkdir(parents=True)
    shutil.copy2(src / manifest["generator"]["path"], work / "tools" / "make_tables.py")
    shutil.copytree(src / "records", work / "records")


def run(cmd: list[str], cwd: Path) -> dict[str, Any]:
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    return {"cmd": cmd, "rc": r.returncode, "stdout_tail": r.stdout[-2000:], "stderr_tail": r.stderr[-2000:]}


def compare_outputs(out: Path, work: Path, manifest: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    for o in manifest["outputs"]:
        f = (out / o["file"]) if o.get("root") == "out" else (work / o["file"])
        if not f.is_file():
            got = None
        elif o.get("compare") == "body":
            got = sha256_body(f)
        else:
            got = sha256_file(f)
        rows.append({"file": o["file"], "exhibits": o.get("exhibits", []), "expected": o["sha256"], "found": got,
                     "ok": got == o["sha256"]})
    return rows


def repinned(src: Path, out: Path, manifest: dict[str, Any], revision: str) -> dict[str, Any]:
    """The manifest rebuilt from `src` (module docstring, "Re-pinning"): runs the generator and the held-out
    test macros in `out`, then pins what it read and wrote."""
    work = out / "work" / "paper3"
    stage(src, work, manifest)
    for cmd, cwd in (([sys.executable, "-I", "tools/make_tables.py"], work),
                     ([sys.executable, "-s", "-B", str(E1_TABLE), "--verdict",
                       str(work / "records" / manifest["e1_verdict_record"]), "--out", str(out / "e1_results.tex")],
                      out)):
        r = run(cmd, cwd)
        if r["rc"] != 0:
            raise SystemExit(f"--repin: {' '.join(cmd)} failed (rc {r['rc']}): {r['stderr_tail']}")
    status = {r["path"]: r.get("release", "NOT RELEASED") for r in manifest["records"]}
    names = {r["path"]: {"release_path": r["release_path"]} for r in manifest["records"] if "release_path" in r}
    records = [{"path": p.relative_to(src).as_posix(), **names.get(p.relative_to(src).as_posix(), {}),
                "sha256": sha256_file(p), "bytes": p.stat().st_size,
                "release": status.get(p.relative_to(src).as_posix(), "NOT RELEASED")}
               for p in sorted((src / "records").rglob("*")) if p.is_file()]
    outputs = []
    for o in manifest["outputs"]:
        f = (out / o["file"]) if o.get("root") == "out" else (work / o["file"])
        if f.is_file():
            new = {**o, "sha256": sha256_body(f) if o.get("compare") == "body" else sha256_file(f)}
            if "released" in o:
                new["released"] = {**o["released"], "content_sha256": sha256_content(f)}
            outputs.append(new)
    listed = {o["file"] for o in manifest["outputs"]}
    for t in sorted((work / "tables").glob("*.tex")) if (work / "tables").is_dir() else []:
        if f"tables/{t.name}" not in listed:
            outputs.append({"file": f"tables/{t.name}", "sha256": sha256_file(t), "exhibits": ["appendix"],
                            "reads": []})
    shutil.rmtree(out / "work")
    (out / "e1_results.tex").unlink(missing_ok=True)
    return {**manifest, "paper_revision": revision,
            "generator": {**manifest["generator"], "sha256": sha256_file(src / manifest["generator"]["path"])},
            "records": records, "outputs": outputs}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--paper-src", type=Path,
                    help="paper source dir (tools/make_tables.py, records/); without it, the released check runs")
    ap.add_argument("--out", type=Path, required=True, help="new or empty directory for the copies and the report")
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--allow-unpinned", action="store_true", help="run even if an input's sha256 differs")
    ap.add_argument("--repin", metavar="REVISION", help="rewrite --manifest from this paper source (module docstring)")
    a = ap.parse_args(argv)
    manifest = json.loads(a.manifest.read_text())
    out = a.out.resolve()
    if out.exists() and any(out.iterdir()):
        ap.error(f"--out {out} is not empty")
    if a.paper_src is None:
        if a.repin or a.allow_unpinned:
            ap.error("--repin and --allow-unpinned need --paper-src")
        out.mkdir(parents=True, exist_ok=True)
        report = released_check(out, manifest)
        (out / "report.json").write_text(json.dumps(report, indent=1) + "\n")
        print(json.dumps({"ok": report["ok"], "mode": "released", "error": report.get("error"),
                          "outputs_checked": len(report["outputs"]),
                          "outputs_mismatched": [r["file"] for r in report["outputs"] if not r["ok"]],
                          "report": str(out / "report.json")}))
        return 0 if report["ok"] else 1
    src = a.paper_src.resolve()
    if out == src or src in out.parents:
        ap.error("--out must be outside --paper-src")
    out.mkdir(parents=True, exist_ok=True)
    inputs = check_inputs(src, manifest)
    report: dict[str, Any] = {"paper_revision": manifest["paper_revision"], "inputs": inputs, "runs": [],
                              "outputs": [], "ok": False}
    missing = [r["path"] for r in inputs if r["found"] is None and not a.repin]
    if a.repin:
        manifest = repinned(src, out, manifest, a.repin)
        a.manifest.write_text(json.dumps(manifest, indent=1) + "\n")
        inputs = check_inputs(src, manifest)
        report["paper_revision"], report["inputs"], report["repinned"] = a.repin, inputs, str(a.manifest)
        report["ok"] = all(r["ok"] for r in inputs)
    elif missing or (not a.allow_unpinned and not all(r["ok"] for r in inputs)):
        report["error"] = ("missing inputs: " + ", ".join(missing)) if missing else "input sha256 mismatch"
    else:
        work = out / "work" / "paper3"
        stage(src, work, manifest)
        report["runs"].append(run([sys.executable, "-I", "tools/make_tables.py"], work))
        report["runs"].append(run([sys.executable, "-s", "-B", str(E1_TABLE), "--verdict",
                                   str(work / "records" / manifest["e1_verdict_record"]),
                                   "--out", str(out / "e1_results.tex")], out))
        report["outputs"] = compare_outputs(out, work, manifest)
        report["ok"] = (all(r["rc"] == 0 for r in report["runs"]) and all(r["ok"] for r in report["outputs"])
                        and all(r["ok"] for r in inputs))
    (out / "report.json").write_text(json.dumps(report, indent=1) + "\n")
    bad = [r["file"] for r in report["outputs"] if not r["ok"]]
    print(json.dumps({"ok": report["ok"], "error": report.get("error"), "outputs_checked": len(report["outputs"]),
                      "outputs_mismatched": bad, "report": str(out / "report.json")}))
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())

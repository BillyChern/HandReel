"""Participant-level partition check for the Ego4D video lists.

The fresh-list selection rule held H_eval_fresh and X_reserve out by PARTICIPANT from L (the 40-video candidate list,
`L_CANDIDATES_LIST`) and S2, but never checked H against X: the two share 7 participants (9 H videos and 9 X videos).
`check_partition` makes that check a refusal, for any named sets:

- every uid is looked up in the Ego4D manifest (`data/ego4d/manifest.csv`, recorded by sha256) as its
  `fb_participant_id`; a uid absent from the manifest is refused (its wearer cannot be known);
- an EVAL set may share no video and no participant with any other set (eval or not);
- a blank participant id is UNKNOWN: refused in an eval set unless its uid is explicitly admitted (`admit_blank`);
  a blank id in a non-eval set cannot be matched and is reported, not refused.

`X_clean` (47 videos, 24.09 h) is X_reserve minus every H participant minus every blank id, derived by
`derive_x_clean` and recorded as the `X_CLEAN_LIST` file (its video list is pinned by sha256). It is the only X pool
(`x_pool`). Metadata only: nothing here opens a video.

The three list files (`FRESH_LISTS`, `L_CANDIDATES_LIST`, `X_CLEAN_LIST`) and the manifest are NOT shipped: they hold Ego4D
video uids and per-video metadata taken from the Ego4D annotations, which the Ego4D licence does not let this
repository redistribute. A licensed user puts the lists in `$FASTDO_EGO4D_LISTS` (default
`<primary checkout>/data/ego4d/lists`, `fastdo.hostpaths.ego4d_lists_dir`) and the manifest at
`<primary checkout>/data/ego4d/manifest.csv`; a missing list raises `Ego4DListMissing`, naming the file, its sha256
and how to obtain it, and a path still under the `/opt/fastdo` placeholder raises `fastdo.hostpaths.HostPathNotSet`.
"""


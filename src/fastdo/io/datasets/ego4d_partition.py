# The one blank-id H_eval_fresh video is held out by VIDEO only (the other 18 of 19 are held out by participant).
# It is admitted by the sha256 of its uid so that the disclosure, not a silent pass, carries it. Ego4D video uids are
# not redistributed, and an unsalted hash of one uid can be matched by anyone who holds the uid list, so the digest
# does not ship either: it is read from `H_BLANK_ADMITTED_FILE` in `$FASTDO_EGO4D_LISTS`, a JSON document
# {"sha256": ["<64 hex characters>"]} that the holder of the lists writes. Without that file no blank is admitted.
H_BLANK_ADMITTED_FILE = "ego4d-h-blank-admitted.json"


def h_blank_admitted_digests() -> frozenset[str]:
    """The sha256 digests of the admitted blank-id uids, from the user's own file; empty when the file is absent.

    Raises:
        ValueError: If the file exists and is not {"sha256": [64-hex strings]}.
    """
    path = hostpaths.ego4d_lists_dir() / H_BLANK_ADMITTED_FILE
    if not path.is_file():
        return frozenset()
    doc = json.loads(path.read_text())
    digests = doc.get("sha256") if isinstance(doc, dict) else None
    if not isinstance(digests, list) or not all(
            isinstance(d, str) and len(d) == 64 and set(d) <= set("0123456789abcdef") for d in digests):
        raise ValueError(f'{path}: expected {{"sha256": [64 lowercase hex characters, ...]}}')
    return frozenset(digests)


def admitted_blank_uids(uids: Iterable[str], digests: frozenset[str] | None = None) -> frozenset[str]:
    """The uids among `uids` whose sha256 (of the uid's utf-8 text) is in `digests` (default: the user's file)."""
    digests = h_blank_admitted_digests() if digests is None else digests
    return frozenset(u for u in uids if hashlib.sha256(u.encode()).hexdigest() in digests)


class Ego4DListMissing(FileNotFoundError):
    """An Ego4D list file is not in `$FASTDO_EGO4D_LISTS`: it is licensed metadata and does not ship."""


class PartitionError(ValueError):
    """A partition refusal; `report` holds the structured findings (shared participants, videos, blanks)."""

    def __init__(self, problems: list[str], report: dict[str, Any]) -> None:
        super().__init__("participant partition refused: " + "; ".join(problems))
        self.problems = problems
        self.report = report


@dataclass(frozen=True)
class PartitionReport:
    """A passed check: per-set video and participant counts, blank ids, the manifest it used."""

    manifest_sha256: str
    eval_sets: tuple[str, ...]
    n_videos: dict[str, int]
    n_participants: dict[str, int]
    blank: dict[str, list[str]] = field(default_factory=dict)
    blank_admitted: list[str] = field(default_factory=list)


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _list_path(spec: Mapping[str, str], what: str) -> Path:
    """The file of a list record: a relative "file" is under `hostpaths.ego4d_lists_dir()`.

    Raises:
        fastdo.hostpaths.HostPathNotSet: While the lists directory is still the /opt/fastdo placeholder.
        Ego4DListMissing: When the file is absent (it does not ship; the message says how to obtain it).
    """
    path = Path(spec["file"])
    if not path.is_absolute():
        path = hostpaths.require(hostpaths.ego4d_lists_dir(), _LIST_VARS) / path
    if not path.is_file():
        pin = spec.get("sha256") or f"video list sha256 {spec.get('videos_sha256')}"
        raise Ego4DListMissing(
            f"the Ego4D {what} {path} is missing. It holds Ego4D video uids selected from the Ego4D annotations, "
            f"which the Ego4D licence does not let this repository redistribute, so it is not shipped. Put the "
            f"file (sha256 {pin}) in ${_LIST_VARS} (now {path.parent}). {_OBTAIN.get(what, '')}".rstrip())
    return path


def _verified(spec: Mapping[str, str], what: str) -> Path:
    """The recorded file ({'file', 'sha256'}), refused unless its sha256 matches. An absolute "file" (the manifest)
    is checked against the /opt/fastdo placeholder; a relative one is a list file (`_list_path`)."""
    path = Path(spec["file"])
    if path.is_absolute():
        hostpaths.require(path, _DATA_VARS)
        if not path.is_file():
            raise FileNotFoundError(f"the {what} {path} does not exist")
    else:
        path = _list_path(spec, what)
    got = _sha256(path)
    if got != spec["sha256"]:
        raise ValueError(f"the {what} {path} has sha256 {got}, not the recorded {spec['sha256']}")
    return path


def normalise_pid(raw: str | None) -> str:
    """The manifest writes ids as floats ('17.0'); '17' and '17.0' are one participant. Blank -> ''."""
    s = (raw or "").strip()
    if not s:
        return ""
    try:
        f = float(s)
    except ValueError:
        return s
    return str(int(f)) if f.is_integer() else s


def load_participants(manifest: Mapping[str, str] | str | Path = MANIFEST) -> tuple[dict[str, str], str]:
    """({video_uid: participant id, '' when blank}, manifest sha256). A {'file', 'sha256'} record is verified; a bare
    path (tests) is read as given."""
    if isinstance(manifest, Mapping):
        path = _verified(manifest, "Ego4D manifest")
    else:
        path = Path(manifest)
    with path.open(newline="") as f:
        rows = {r["video_uid"]: normalise_pid(r.get("fb_participant_id")) for r in csv.DictReader(f)}
    return rows, _sha256(path)


def check_partition(sets: Mapping[str, Sequence[str]], manifest_path: Mapping[str, str] | str | Path = MANIFEST,
                    eval_sets: Iterable[str] = (), admit_blank: Iterable[str] = frozenset()) -> PartitionReport:
    """Refuse (PartitionError) unless every eval set is disjoint BY PARTICIPANT (and by video) from every other set.

 `sets` maps a set name to its video uids; `eval_sets` names the held-out sets (at least one, all in `sets`);
    `admit_blank` lists the eval uids with a blank participant id that are explicitly admitted (held out by video only).
    A uid absent from the manifest, a repeated uid within a set, or an `admit_blank` uid that is not a blank-id eval
    video is also refused."""
    evals = tuple(dict.fromkeys(eval_sets))
    admit = frozenset(admit_blank)
    if not evals:
        raise ValueError("check_partition needs at least one eval set")
    unknown = [e for e in evals if e not in sets]
    if unknown:
        raise ValueError(f"eval sets not among the sets: {unknown}")
    pid, sha = load_participants(manifest_path)
    problems: list[str] = []
    report: dict[str, Any] = {"manifest_sha256": sha, "eval_sets": list(evals), "missing": {}, "repeated": {},
                              "shared_videos": {}, "shared_participants": {}, "blank_refused": {},
                              "blank_admitted": [], "admit_unused": []}
    for name, uids in sets.items():
        miss = sorted({u for u in uids if u not in pid})
        if miss:
            report["missing"][name] = miss
            problems.append(f"{name}: {len(miss)} uid(s) not in the manifest {miss}")
        if len(set(uids)) != len(uids):
            report["repeated"][name] = sorted({u for u in uids if list(uids).count(u) > 1})
            problems.append(f"{name} repeats a video")
    by_set = {n: {u: pid.get(u, "") for u in uids} for n, uids in sets.items()}
    pids = {n: {p for p in m.values() if p} for n, m in by_set.items()}
    done: set[frozenset[str]] = set()
    for e in evals:
        for other in sets:
            if other == e or frozenset((e, other)) in done:
                continue
            done.add(frozenset((e, other)))
            vids = sorted(set(sets[e]) & set(sets[other]))
            if vids:
                report["shared_videos"][f"{e}|{other}"] = vids
                problems.append(f"{e} and {other} share {len(vids)} video(s)")
            shared = sorted(pids[e] & pids[other], key=_pid_key)
            if shared:
                rec = {"pids": shared,
                       e: sorted(u for u, p in by_set[e].items() if p in shared),
                       other: sorted(u for u, p in by_set[other].items() if p in shared)}
                report["shared_participants"][f"{e}|{other}"] = rec
                problems.append(f"{e} and {other} share {len(shared)} participant(s) {shared} "
                                f"({len(rec[e])} + {len(rec[other])} videos)")
        blanks = sorted(u for u, p in by_set[e].items() if not p and u in pid)
        refused = [u for u in blanks if u not in admit]
        report["blank_admitted"] += [u for u in blanks if u in admit]
        if refused:
            report["blank_refused"][e] = refused
            problems.append(f"{e}: {len(refused)} video(s) with no participant id, not admitted by `admit_blank` "
                            f"{refused}")
    eval_blanks = {u for e in evals for u, p in by_set[e].items() if not p and u in pid}
    report["admit_unused"] = sorted(admit - eval_blanks)
    if report["admit_unused"]:
        problems.append(f"admit_blank lists uid(s) that are not blank-id eval videos {report['admit_unused']}")
    if problems:
        raise PartitionError(problems, report)
    return PartitionReport(manifest_sha256=sha, eval_sets=evals,
                           n_videos={n: len(u) for n, u in sets.items()},
                           n_participants={n: len(p) for n, p in pids.items()},
                           blank={n: sorted(u for u, p in m.items() if not p) for n, m in by_set.items()},
                           blank_admitted=sorted(report["blank_admitted"]))


def _pid_key(p: str) -> tuple[int, Any]:
    return (0, int(p)) if p.isdigit() else (1, p)


# ------------------------------------------------------------------------------------------------ the lists
def fresh_lists(spec: Mapping[str, str] = FRESH_LISTS) -> tuple[list[str], list[str]]:
    """(H_eval_fresh, X_reserve) uids in list order, from the fresh-lists file verified by sha256."""
    doc = json.loads(_verified(spec, "fresh lists").read_text())
    return list(doc["H_eval_fresh"]["videos"]), list(doc["X_reserve"]["videos"])


def l_candidate_videos(spec: Mapping[str, str] = L_CANDIDATES_LIST) -> list[str]:
    """The L list's 40 chosen videos, from the candidates file verified by sha256."""
    return [c["video_uid"] for c in json.loads(_verified(spec, "L candidates").read_text())["chosen"]]


def s2_videos(root: Path = S2_VIDEOS) -> list[str]:
    """The S2 videos as the fresh-list rule read them: the .mp4 names in the S2 directory (a listing, no read)."""
    names = sorted(f[:-4] for f in os.listdir(hostpaths.require(root, _DATA_VARS)) if f.endswith(".mp4"))
    if not names:
        raise FileNotFoundError(f"no S2 videos listed under {root}")
    return names


def derive_x_clean(h: Sequence[str], x: Sequence[str],
                   manifest: Mapping[str, str] | str | Path = MANIFEST) -> list[str]:
    """X_reserve minus every video whose participant is in H, minus every blank-id video (X order kept)."""
    pid, _ = load_participants(manifest)
    h_pids = {pid.get(u, "") for u in h} - {""}
    return [u for u in x if pid.get(u, "") and pid[u] not in h_pids]


def x_clean_videos(spec: Mapping[str, str] = X_CLEAN_LIST) -> list[str]:
    """The X_clean list. A record with "sha256" pins the file's bytes, one with "videos_sha256" its video list
    (`json.dumps(videos)`); a record with neither is read unchecked."""
    path = _verified(spec, "X_clean list") if "sha256" in spec else _list_path(spec, "X_clean list")
    doc = json.loads(path.read_text())
    vids = list(doc["videos"])
    if doc.get("n") != len(vids):
        raise ValueError(f"the X_clean list states n={doc.get('n')} but lists {len(vids)} videos")
    if "videos_sha256" in spec:
        got = hashlib.sha256(json.dumps(vids).encode()).hexdigest()
        if got != spec["videos_sha256"]:
            raise ValueError(f"the X_clean list {path} has video-list sha256 {got}, not the recorded "
                             f"{spec['videos_sha256']}")
    return vids


def x_pool(manifest: Mapping[str, str] | str | Path = MANIFEST) -> list[str]:
    """THE X pool: X_clean, refused unless it is partitioned by participant from
    H_eval_fresh (the eval set, its blank admitted by the user's `H_BLANK_ADMITTED_FILE`), L (`l_candidate_videos`) and S2."""
    h, _ = fresh_lists()
    xc = x_clean_videos()
    check_partition({"H_eval_fresh": h, "X_clean": xc, "L": l_candidate_videos(), "S2": s2_videos()},
                    manifest, eval_sets=("H_eval_fresh",), admit_blank=admitted_blank_uids(h))
    pid, _ = load_participants(manifest)
    if any(not pid.get(u) for u in xc):
        raise PartitionError(["X_clean holds a blank-id video"], {})
    return xc


def _write_x_clean(out: Path) -> dict[str, Any]:
    """Derive X_clean from the recorded lists and manifest and write it (the committed file is this output)."""
    h, x = fresh_lists()
    xc = derive_x_clean(h, x)
    with hostpaths.require(MANIFEST["file"], _DATA_VARS).open(newline="") as f:
        dur = {r["video_uid"]: float(r["duration_sec"]) for r in csv.DictReader(f)}
    doc = {"rule": "X_reserve minus every video whose fb_participant_id is in H_eval_fresh, minus every blank-id "
                   "video; X_reserve order (fastdo.io.datasets.ego4d_partition.derive_x_clean)",
           "source": {"fresh_lists_sha256": FRESH_LISTS["sha256"], "manifest_sha256": MANIFEST["sha256"]},
           "videos": xc, "n": len(xc), "hours": round(sum(dur[u] for u in xc) / 3600, 2)}
    out.write_text(json.dumps(doc, indent=1) + "\n")
    return doc



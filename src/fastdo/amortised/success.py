"""Success store and closed-loop CPU certification.

Candidate: a training episode that started at row 0 (the executor's start state, no reference-state initialisation)
with assist level alpha = 0 and passed SR_MT + M_i + PLAUS on its own rollout (the registered scorer,
passed in as `scorer`). It is stored with everything a certificate needs: the clip, the
episode's noise seed (`fastdo.amortised.acting.step_noise`) and the policy version of every step (content-addressed
actor snapshots, written next to the candidate).

`SuccessStore.offer` REFUSES (and says why) an episode with alpha > 0 ("assist": the object wrench helped), one that
started at a row > 0 ("rsi": not the executor's start state) and one whose score is not a success. Storing is
idempotent per (task, episode), so a run resumed from a checkpoint that re-offers the same candidate leaves the store
unchanged.

`certify` re-executes the candidate CLOSED LOOP on the CPU certifier (`TrackerEnv` with `evaluation=True`: only the
executor's own termination and the clip end; DO AS I DO's executor semantics through `CpuWorlds`), from row 0, alpha
0, with the stored noise (regenerated by the candidate's own generator, `acting.noise_for`: "torch" on the CPU path,
"hash" on the device path) and the stored versions loaded by sha256 (`PolicyVersions.load` refuses other bytes). The
certificate's CPU trajectory is the deliverable and must pass the scorer itself; it is certified only if it ran the
clip to its end. CPU MuJoCo and batch-of-one acting are deterministic, so two re-executions are bit-identical
(`Certificate.sha`).
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Callable, Sequence
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from fastdo.amortised.acting import PolicyVersions, act, noise_for
from fastdo.amortised.sac import Actor
from fastdo.amortised.tracker_env import TipSpec, TrackerEnv
from fastdo.amortised.tracker_obs import RefTable, TrackerConfig, observe
from fastdo.transductive.clip import ClipSpec

__all__ = ["Candidate", "Certificate", "SuccessStore", "certify", "trajectory_sha"]

Scorer = Callable[[np.ndarray], dict[str, Any]]


def trajectory_sha(qpos: np.ndarray, ctrl: np.ndarray) -> str:
    """sha256 over the raw float64 bytes of executed states and controls."""
    h = hashlib.sha256()
    for a in (qpos, ctrl):
        a = np.ascontiguousarray(np.asarray(a, np.float64))
        h.update(str(a.shape).encode())
        h.update(a.tobytes())
    return h.hexdigest()


@dataclass(frozen=True)
class Candidate:
    """A training episode offered to the store (module docstring)."""

    task: str
    clip: int
    episode: int
    noise_seed: int
    start_row: int
    alpha: float
    versions: tuple[str, ...]          # policy version of every policy step, in order
    rows: int                          # executed rows
    traj_sha: str                      # `trajectory_sha` of the training rollout
    score: dict[str, Any] = field(default_factory=dict)
    noise: str = "torch"               # the acting noise generator (`acting.NOISE_KINDS`; "hash" on the device path)

    @property
    def steps(self) -> int:
        return len(self.versions)

    def to_json(self) -> str:
        d = asdict(self)
        d["versions"] = list(self.versions)
        if d["noise"] == "torch":          # the CPU path's bytes are unchanged by the device path's field
            del d["noise"]
        return json.dumps(d, sort_keys=True, default=float)

    @staticmethod
    def from_json(text: str) -> Candidate:
        d = json.loads(text)
        d["versions"] = tuple(d["versions"])
        return Candidate(**d)


class SuccessStore:
    """`<root>/<task>/<episode>.json` per stored candidate and `<root>/snapshots/<sha>.bin` (module docstring)."""

    def __init__(self, root: Path) -> None:
        self.root = Path(root)

    def offer(self, cand: Candidate, versions: PolicyVersions) -> tuple[bool, str]:
        """(stored, reason). Reasons: stored, exists, assist, rsi, not_success."""
        if cand.alpha > 0.0:
            return False, "assist"
        if cand.start_row != 0:
            return False, "rsi"
        if not cand.score.get("success"):
            return False, "not_success"
        path = self.root / cand.task / f"{cand.episode:09d}.json"
        text = cand.to_json()
        if path.is_file():
            if path.read_text() != text:
                raise RuntimeError(f"{path}: a different candidate is stored under the same episode")
            return True, "exists"
        versions.write(cand.versions, self.root / "snapshots")
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(text)
        tmp.replace(path)
        return True, "stored"

    def candidates(self, task: str | None = None) -> list[Candidate]:
        pats = [self.root / task] if task is not None else sorted(p for p in self.root.iterdir()
                                                                  if p.is_dir() and p.name != "snapshots")
        out = []
        for d in pats:
            out += [Candidate.from_json(p.read_text()) for p in sorted(d.glob("*.json"))]
        return out

    def versions(self) -> PolicyVersions:
        return PolicyVersions(self.root / "snapshots")


@dataclass(eq=False)
class Certificate:
    task: str
    episode: int
    qpos: np.ndarray
    ctrl: np.ndarray
    end: str
    score: dict[str, Any]
    certified: bool
    reason: str

    @property
    def sha(self) -> str:
        return trajectory_sha(self.qpos, self.ctrl)

    def summary(self) -> dict[str, Any]:
        return {"task": self.task, "episode": self.episode, "rows": int(self.qpos.shape[0]), "end": self.end,
                "certified": self.certified, "reason": self.reason, "sha": self.sha,
                "score": {k: v for k, v in self.score.items() if not isinstance(v, (list, np.ndarray))}}


def certify(cand: Candidate, spec: ClipSpec, tip: TipSpec, sdf: Any, entry: dict[str, Any], cfg: TrackerConfig,
            actor: Actor, versions: PolicyVersions, scorer: Scorer) -> Certificate:
    """Closed-loop CPU re-execution of `cand` (module docstring). `actor` is only an architecture template: every
    weight it acts with is loaded from `versions` by the candidate's sha256s. `entry` is the clip's `RefTable` entry
    (`clip_table_entry`), the same one training observed."""
    table = RefTable.stack([entry])
    env = TrackerEnv(cfg, [spec], table, [tip], [sdf], [0], evaluation=True)
    env.next_alpha[:] = 0.0
    rec = env.reset_all()
    qs: list[np.ndarray] = []
    cs: list[np.ndarray] = []
    end, loaded = None, None
    for j, ver in enumerate(cand.versions):
        if ver != loaded:
            versions.load(actor, ver)
            loaded = ver
        obs, _ = observe(table, rec, cfg)
        out = env.step(act(actor, obs, noise_for(cand.noise, cand.noise_seed, j, table.R)[None]))
        qs.append(out.qpos_rows[0])
        cs.append(out.ctrl_rows[0])
        rec = out.record
        if out.end[0] is not None:
            end = out.end[0]
            break
    qpos = np.concatenate(qs) if qs else np.zeros((0, spec.ex.model.nq))
    ctrl = np.concatenate(cs) if cs else np.zeros((0, spec.ex.model.nu))
    if end is None:
        return Certificate(cand.task, cand.episode, qpos, ctrl, "versions_exhausted", {}, False, "versions_exhausted")
    score = scorer(qpos)
    ok = end == "clip_end" and bool(score.get("success"))
    return Certificate(cand.task, cand.episode, qpos, ctrl, end, score, ok,
                       "certified" if ok else ("not_success" if end == "clip_end" else end))


def certify_all(store: SuccessStore, specs: Sequence[ClipSpec], tips: Sequence[TipSpec], sdfs: Sequence[Any],
                entries: Sequence[dict[str, Any]], cfg: TrackerConfig, actor: Actor, scorers: Sequence[Scorer],
                tasks: Sequence[str]) -> list[Certificate]:
    """Certify every stored candidate of the given clips (in store order)."""
    vers = store.versions()
    out = []
    for c in store.candidates():
        i = list(tasks).index(c.task)
        out.append(certify(c, specs[i], tips[i], sdfs[i], entries[i], cfg, actor, vers, scorers[i]))
    return out

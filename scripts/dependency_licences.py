"""Write the licence table of every package in `uv.lock`, read from the installed packages' metadata.

    uv run --frozen python scripts/dependency_licences.py                  # print the table
    uv run --frozen python scripts/dependency_licences.py --write          # replace the table in THIRD_PARTY_LICENSES.md
    uv run --frozen python scripts/dependency_licences.py --check          # exit 1 if that table is out of date

Run it in the environment `uv sync --frozen` builds (add the extras you want covered). For each locked package the
licence is the installed distribution's `License-Expression`, else its `License` field (first line), else its
`License ::` classifiers. A locked package that is not installed, or installed at another version, is listed as such:
its licence was not read. Packages of this repository (path sources) are marked as such. The table is a listing of
declared metadata, not a legal review.
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import sys
import tomllib
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
LOCK = REPO / "uv.lock"
DOC = REPO / "THIRD_PARTY_LICENSES.md"
BEGIN = "<!-- BEGIN generated by scripts/dependency_licences.py -->"
END = "<!-- END generated by scripts/dependency_licences.py -->"
# Packages whose `License` field holds the full licence text with a rule line first, and no SPDX
# expression: the SPDX id the text names. kiwisolver: "the Modified BSD License (also known as New
# or Revised BSD)".
FULL_TEXT_LICENCE = {"kiwisolver": "BSD-3-Clause"}


def source_of(pkg: dict[str, Any]) -> str:
    src = pkg.get("source", {})
    if "git" in src:
        url, _, rev = str(src["git"]).partition("#")
        return f"git {url.split('?')[0]} @ {rev[:8] or '?'}"
    if "path" in src or "editable" in src or "virtual" in src:
        return "this repository"
    return "PyPI" if "registry" in src else "other"


def licence_of(name: str, version: str) -> str:
    try:
        dist = md.distribution(name)
    except md.PackageNotFoundError:
        return "not installed in this environment (not read)"
    meta = dist.metadata
    have = meta.get("Version", "")
    if have.split("+")[0] != version.split("+")[0]:
        return f"installed at {have}, not {version} (not read)"
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr
    lic = (meta.get("License") or "").strip()
    if name.lower() in FULL_TEXT_LICENCE:
        return FULL_TEXT_LICENCE[name.lower()]
    if lic and lic.upper() != "UNKNOWN":
        first = lic.splitlines()[0].strip()
        return first if len(first) <= 80 else first[:77] + "..."
    classes = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    return "; ".join(classes) if classes else "no licence in the metadata"


def table(lock: Path = LOCK) -> str:
    pkgs = tomllib.loads(lock.read_text())["package"]
    rows = ["| Package | Version | Source | Licence (declared metadata) |", "|---|---|---|---|"]
    for p in sorted(pkgs, key=lambda q: q["name"].lower()):
        src = source_of(p)
        lic = "this repository (Apache-2.0)" if src == "this repository" else licence_of(p["name"], p["version"])
        rows.append(f"| {p['name']} | {p['version']} | {src} | {lic.replace('|', '/')} |")
    return "\n".join(rows) + "\n"


def splice(doc: str, body: str) -> str:
    a, b = doc.index(BEGIN), doc.index(END)
    return doc[:a + len(BEGIN)] + "\n" + body + doc[b:]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--lock", type=Path, default=LOCK)
    ap.add_argument("--doc", type=Path, default=DOC)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="replace the generated table in --doc")
    g.add_argument("--check", action="store_true", help="exit 1 when the table in --doc differs from a fresh one")
    a = ap.parse_args(argv)
    body = table(a.lock)
    if not (a.write or a.check):
        sys.stdout.write(body)
        return 0
    doc = a.doc.read_text()
    new = splice(doc, body)
    if a.check:
        if new != doc:
            print(f"{a.doc}: the dependency table is out of date; run with --write", file=sys.stderr)
            return 1
        return 0
    a.doc.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Writes `e1_results.tex`: the E1 held-out results as LaTeX macros (`\\Eone...`), from the verdict record (the JSON
passed as `--verdict`) and nothing else. Without a record every macro is `\\TBDr`. The paper source `\\input`s this
file, but no table or section of the paper's main text prints these macros: the paper source writes its Table 1 by
hand.

    python run/paper/e1_table.py [--verdict <date>-e1-verdict.json] [--out paper/e1_results.tex]

Cells per corpus c in {H, D}: assigned / run (stops at the 80% bar), delivered per side, the O-EST primary's
paired median ratio, 95% CI and verdict, the S2 O-CAL ratio, CI, deliveries and verdict, the LOWER ERROR suffix of each
arm (", lower error" when the record's lower_error is true, else empty), and the headline flag. Deliveries are over
the ANALYSED units (after the paired removal of INFRA-UNRESOLVED units).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

CORPORA = {"H": "H", "D": "D"}
FIELDS = ("Assigned", "Run", "Analysed", "DelOurs", "DelTheirs", "EstRatio", "EstCI", "EstVerdict", "EstLower",
          "CalDelOurs", "CalDelTheirs", "CalRatio", "CalCI", "CalVerdict", "CalLower", "Headline")
SUFFIX_FIELDS = ("EstLower", "CalLower")                     # empty without a record, so no doubled placeholder
PENDING = r"\TBDr"


def _ratio(x: Any) -> str:
    return PENDING if x is None else f"{float(x):.2f}"


def _ci(ci: Any) -> str:
    import math
    if not ci or None in ci:
        return PENDING
    lo, hi = (math.exp(float(v)) for v in ci)               # the record's CIs are on the log-ratio scale
    return f"[{lo:.2f}, {hi:.2f}]"


def cells(rec: dict[str, Any] | None) -> dict[str, dict[str, str]]:
    """Per corpus, the macro values; every value is PENDING without a record."""
    out = {c: {f: "" if f in SUFFIX_FIELDS else PENDING for f in FIELDS} for c in CORPORA}
    if rec is None:
        return out
    est = rec["primary_O_EST"]["primary"]["corpora"]
    cal = rec["secondary_S2_O_CAL"]["primary"]["corpora"]
    for c in CORPORA:
        e, k = est[c], cal[c]
        out[c] = {"Assigned": str(e["n_assigned"]), "Run": str(e["n_run"]), "Analysed": str(e["n_analysed"]),
                  "DelOurs": str(e["delivered_ours"]),
                  "DelTheirs": str(e["delivered_theirs"]), "EstRatio": _ratio(e["itt"].get("ratio")),
                  "EstCI": _ci(e["itt"].get("ci95")), "EstVerdict": str(e["verdict"]).lower(),
                  "EstLower": ", lower error" if e.get("lower_error") else "",
                  "CalDelOurs": str(k["delivered_ours"]), "CalDelTheirs": str(k["delivered_theirs"]),
                  "CalRatio": _ratio(k["itt"].get("ratio")), "CalCI": _ci(k["itt"].get("ci95")),
                  "CalVerdict": str(k["verdict"]).lower(),
                  "CalLower": ", lower error" if k.get("lower_error") else "",
                  "Headline": "yes" if rec["headline"][c]["headline_non_inferior"] else "no"}
    return out


def render(rec: dict[str, Any] | None, source: str) -> str:
    lines = [f"% GENERATED by run/paper/e1_table.py from {source}; do not edit by hand."]
    for c, vals in cells(rec).items():
        for f in FIELDS:
            lines.append(f"\\providecommand{{\\Eone{c}{f}}}{{}}\\renewcommand{{\\Eone{c}{f}}}{{{vals[f]}}}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--verdict", type=Path)
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[2] / "paper" / "e1_results.tex")
    a = ap.parse_args(argv)
    rec = json.loads(a.verdict.read_text()) if a.verdict else None
    a.out.write_text(render(rec, a.verdict.as_posix() if a.verdict else "no verdict record (pending)"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
